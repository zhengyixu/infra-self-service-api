#!/usr/bin/env python3
"""Generate an Ansible inventory from Terraform outputs.

Usage (from the repo root), for one environment:
    ENVIRONMENT_ID=<uuid> scripts/tf.sh environment floci output -json \
        | python3 ansible/inventory/generate.py > ansible/inventory/generated.yml

Terraform is the source of truth for which hosts exist. Target-specific
connection details (login user, host key policy) are decided here, so the
playbooks stay identical for Floci and real AWS.
"""
import json
import sys

SSH_KEY = "~/.ssh/infra-self-service-api"


def main() -> None:
    tf = {name: out["value"] for name, out in json.load(sys.stdin).items()}
    target = tf["target"]

    if target == "floci":
        # Floci instances are recreated with new host keys on reused IPs, so a
        # known_hosts entry would break every rebuild. Acceptable only locally.
        ssh_args = "-o StrictHostKeyChecking=no -o UserKnownHostsFile=/dev/null"
    else:
        # Real AWS: trust on first use, then pin the host key.
        ssh_args = "-o StrictHostKeyChecking=accept-new"

    lines = [
        "# GENERATED by ansible/inventory/generate.py from Terraform outputs. Do not edit.",
        "all:",
        "  vars:",
        f"    target: {target}",
        f"    ansible_user: {tf['ssh_user']}",
        f"    ansible_ssh_private_key_file: {SSH_KEY}",
        f'    ansible_ssh_common_args: "{ssh_args}"',
        f"    artifacts_bucket: {tf['artifacts_bucket']}",
        f"    environment_id: {tf['environment_id']}",
        f"    environment_name: {tf['environment_name']}",
        "  children:",
        "    app:",
        "      hosts:" + ("" if tf["instances"] else " {}"),
    ]
    for name, inst in sorted(tf["instances"].items()):
        lines += [
            f"        {name}:",
            f"          ansible_host: {inst['public_ip']}",
            f"          instance_id: {inst['id']}",
        ]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
